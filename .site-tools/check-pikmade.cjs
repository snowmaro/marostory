const { chromium, webkit } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const out = '/tmp/pikmade-preview';
const base = process.env.PIKMADE_PREVIEW_URL || 'http://127.0.0.1:4173';
(async () => {
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ headless:true });
  const context = await browser.newContext({ viewport:{width:1440,height:1000}, permissions:['clipboard-read','clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  const response = await page.goto(base + '/project/pikmade', {waitUntil:'networkidle'});
  assert.equal(response.status(), 200);
  const html = await response.text();
  assert(html.includes('og:image') && html.includes('사진 한 장') && html.includes('https://marostory.com/project/pikmade'));
  await page.screenshot({path:out+'/desktop-hero.png'});
  await page.locator('[data-pick=figure]').click();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('#active-style-name').textContent(), '3D 피규어');
  assert((await page.locator('#compare-source').getAttribute('src')).includes('original-figure.webp'));
  await page.locator('[data-style=crayon]').click();
  assert((await page.locator('#compare-source').getAttribute('src')).includes('original-crayon.webp'));
  await page.locator('[data-style=paper]').click();
  assert((await page.locator('#compare-source').getAttribute('src')).includes('/original.webp'));
  await page.locator('#compare-range').fill('70');
  assert.equal(await page.locator('#transform .compare-frame').evaluate(el=>el.style.getPropertyValue('--split')), '70%');
  await page.locator('#transform .transform-stage').screenshot({path:out+'/desktop-compare.png'});
  await page.locator('[data-filter="3d"]').click();
  assert.equal(await page.locator('.gallery-card:visible').count(), 1);
  await page.locator('.gallery-card:visible').click();
  assert.equal(await page.locator('#art-title').textContent(), '3D 피규어');
  assert(await page.locator('#art-dialog').evaluate(el=>el.open));
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#art-dialog').evaluate(el=>el.open)));
  await page.locator('[data-filter=all]').click();
  await page.locator('#styles').screenshot({path:out+'/desktop-gallery.png'});
  await page.locator('[data-filter=together]').click();
  assert.equal(await page.locator('.gallery-card:visible').count(), 4);
  await page.locator('[data-filter=all]').click();
  assert.equal(await page.locator('.gallery-card:visible').count(), 9);
  await page.locator('#restore-range').fill('72');
  for (const [key, source] of [['family-color','family-original'], ['family-clean','family-original'], ['woman-clean','woman-original']]) {
    await page.locator(`[data-restore="${key}"]`).click();
    assert((await page.locator('#restore-source').getAttribute('src')).includes(`restore-${source}.webp`));
    assert((await page.locator('#restore-result').getAttribute('src')).includes(`restore-${key}.webp`));
    assert.equal(await page.locator(`[data-restore="${key}"]`).getAttribute('aria-pressed'), 'true');
  }
  await page.locator('[data-restore="family-color"]').click();
  assert(!(await page.locator('#restore').textContent()).includes('Wikimedia'));
  assert.equal(await page.locator('.restore-frame').evaluate(el=>el.style.getPropertyValue('--split')), '72%');
  await page.locator('#restore').screenshot({path:out+'/desktop-restore.png'});
  await page.locator('[data-step="2"]').click();
  assert.equal(await page.locator('[data-screen="2"]').getAttribute('aria-hidden'), 'false');
  await page.locator('.faq-list summary').first().click();
  assert(await page.locator('.faq-list details').first().evaluate(el=>el.open));
  await page.locator('.site-header .share-button').click();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()), 'https://marostory.com/project/pikmade');
  const sizes = [{width:1440,height:1000},{width:1024,height:768},{width:768,height:1024},{width:390,height:844},{width:320,height:740}];
  for (const lang of ['ko','en']) {
    for (const size of sizes) {
      await page.setViewportSize(size);
      await page.goto(base + '/project/pikmade' + (lang==='en'?'/en':''), {waitUntil:'networkidle'});
      assert.equal(await page.locator('html').getAttribute('lang'), lang);
      assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1), `${lang} overflow at ${size.width}`);
      for (const id of ['styles','restore','how','download']) { await page.locator('#'+id).scrollIntoViewIfNeeded(); await page.waitForTimeout(100); }
      const missing = await page.locator('img').evaluateAll(images=>images.filter(image=>image.getAttribute('src') && image.complete && !image.naturalWidth).map(image=>image.src));
      assert.deepEqual(missing, []);
      await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
      if(size.width===390) await page.screenshot({path:out+`/${lang}-mobile-hero.png`});
      if(size.width===1440 && lang==='en') await page.screenshot({path:out+'/en-desktop-hero.png'});
    }
  }
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/project/pikmade',{waitUntil:'networkidle'});
  await page.locator('#styles').scrollIntoViewIfNeeded();
  await page.waitForTimeout(400);
  assert(await page.locator('.mobile-download').evaluate(el=>el.classList.contains('visible')));
  await page.locator('#styles').screenshot({path:out+'/mobile-gallery.png'});
  await page.locator('#restore-range').fill('30');
  await page.locator('[data-restore="woman-clean"]').click();
  await page.locator('#restore').screenshot({path:out+'/mobile-restore.png'});
  await page.locator('#how').screenshot({path:out+'/mobile-how.png'});
  await page.locator('#download').scrollIntoViewIfNeeded();
  await page.waitForTimeout(400);
  assert(!(await page.locator('.mobile-download').evaluate(el=>el.classList.contains('visible'))));
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.ticker>div').evaluate(el=>getComputedStyle(el).animationName), 'none');
  await page.goto(base+'/project/pikmade',{waitUntil:'networkidle'});
  assert.equal(await page.locator('.transform-stage').evaluate(el=>getComputedStyle(el).position), 'static');
  assert.deepEqual(errors, []);
  const noJS = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const staticPage = await noJS.newPage();
  await staticPage.goto(base+'/project/pikmade');
  assert(await staticPage.locator('h1').isVisible());
  assert.equal(await staticPage.locator('.hero .store-links a').count(), 2);
  assert.equal(await staticPage.locator('meta[property="og:image"]').getAttribute('content'), 'https://marostory.com/assets/pikmade/og-ko.jpg?v=20261011');
  await browser.close();
  const safari = await webkit.launch({headless:true});
  const safariPage = await safari.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await safariPage.goto(base+'/project/pikmade',{waitUntil:'networkidle'});
  assert(await safariPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await safariPage.locator('[data-style=crayon]').click();
  assert.equal(await safariPage.locator('#active-style-name').textContent(),'크레파스');
  await safariPage.locator('[data-filter="3d"]').click();
  await safariPage.locator('.gallery-card:visible').click();
  assert(await safariPage.locator('#art-dialog').evaluate(el=>el.open));
  await safariPage.locator('#art-dialog .dialog-close').click();
  await safariPage.locator('[data-restore="family-clean"]').click();
  assert((await safariPage.locator('#restore-result').getAttribute('src')).includes('restore-family-clean.webp'));
  await safariPage.locator('#restore-range').fill('80');
  assert.equal(await safariPage.locator('.restore-frame').evaluate(el=>el.style.getPropertyValue('--split')), '80%');
  await safari.close();
  console.log('PASS: KO/EN, 320–1440px, Chromium + WebKit, comparison, filters, modal, steps, sharing, store links, sticky CTA, reduced motion, no-JS metadata. Screenshots: '+out);
})().catch(error=>{console.error(error);process.exit(1)});
